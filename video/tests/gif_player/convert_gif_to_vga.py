def convert_gif_to_vga(input_path, output_path):
    # Load the original GIF
    with Image.open(input_path) as img:
        # Create a palette image to use as a template
        vga_palette = generate_vga_palette()
        palette_img = Image.new('P', (1, 1))
        palette_img.putpalette(vga_palette)

        frames = []

		# Background color to flatten transparency onto (white)
        bg_color = (255, 255, 255)

		# Process every frame for animated GIFs
        try:
            while True:
                # Get current frame as RGBA to keep any alpha channel
                frame_rgba = img.convert('RGBA')

				# Create a solid background and composite the frame onto it to remove transparency
                background = Image.new('RGBA', img.size, bg_color + (255,))
                composited = Image.alpha_composite(background, frame_rgba)

				# Convert to RGB (no alpha) then quantize to the VGA palette (Nearest Neighbor)
                new_frame = composited.convert('RGB').quantize(palette=palette_img, dither=Image.Dither.NONE)
                frames.append(new_frame)

                img.seek(img.tell() + 1)
        except EOFError:
            pass

        # Save the result
        frames[0].save(
            output_path,
            save_all=True,
            append_images=frames[1:],
            loop=img.info.get('loop', 0),
            duration=img.info.get('duration', 100),
            palette=palette_img.getpalette()
        )
    print(f"Successfully converted '{input_path}' to VGA palette at '{output_path}'")

