def generate_c_array():
    print("const uint8_t vga_palette_6bit[] = {")
    for i, (r, g, b) in enumerate(palette_vga):
        # Convert 6-bit per channel input (0-63) to 2-bit per channel
        # Take the top 2 bits of the 6-bit value
        r_2bit = (r >> 4) & 0x03
        g_2bit = (g >> 4) & 0x03
        b_2bit = (b >> 4) & 0x03
        
        # Combine into BBGGRR
        pixel = (b_2bit << 4) | (g_2bit << 2) | r_2bit
        
        # Format as hex string
        end = ", "
        if (i + 1) % 16 == 0:
            end = ",\n    "
        if i == len(palette_vga) - 1:
            end = ""
            
        print(f"0x{pixel:02x}", end=end)
        
    print("\n};")

if __name__ == "__main__":
    generate_c_array()
